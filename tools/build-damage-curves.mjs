// Writes src/damage-curves.js from USACE go-consequences' occupancy types (structures/occtypes.json, MIT licence): per
// occupancy type the freshwater depth–damage function for the structure and its contents, as depth above the first
// floor (ft) → damage (% of value), mean and standard deviation (the file's Normal distributions; deterministic ones get
// sd 0). Run again to refresh from the repository:  node tools/build-damage-curves.mjs [path/to/occtypes.json]
import { readFileSync, writeFileSync } from 'node:fs';

const SRC = 'https://raw.githubusercontent.com/USACE/go-consequences/main/structures/occtypes.json';
const arg = process.argv[2];
const json = arg ? JSON.parse(readFileSync(arg, 'utf8')) : await (await fetch(SRC)).json();
const out = {};
for (const [name, ot] of Object.entries(json.occupancytypes)) {
  const comp = {};
  for (const part of ['structure', 'contents']) {
    const fs = ot.componentdamagefunctions?.[part]?.damagefunctions ?? {}, f = fs.depth ?? fs.default;
    const df = f?.damagefunction; if (!df?.xvalues?.length) continue;
    const mean = [], sd = [];
    for (const y of df.ydistributions) {
      const p = y.parameters ?? {};
      if (y.type === 'NormalDistribution') { mean.push(p.mean); sd.push(p.standarddeviation); }
      else if (y.type === 'DeterministicDistribution') { mean.push(p.value); sd.push(0); }
      else throw new Error(`${name} ${part}: distribution ${y.type} not handled`);
    }
    const r = (v) => Math.round(v * 100) / 100;
    comp[part] = { x: df.xvalues, mean: mean.map(r), sd: sd.map(r), source: f.source };
  }
  if (comp.structure) out[name] = comp;
}
const body = `// Generated by tools/build-damage-curves.mjs from USACE go-consequences, structures/occtypes.json (MIT licence,
// https://github.com/USACE/go-consequences), ${new Date().toISOString().slice(0, 10)}. Do not edit by hand.
// Per occupancy type: freshwater depth above the first floor (ft) → damage, % of the structure's or the contents' value;
// mean and standard deviation at each depth. Sources as the file gives them (USACE EGM 01-03 / 04-01 for single-family
// homes, HEC-FIA (Galveston District) for the others, FEMA coastal PFRA curves for homes on piers).
export const CURVES = ${JSON.stringify(out)};
`;
writeFileSync(new URL('../src/damage-curves.js', import.meta.url), body);
console.log(`${Object.keys(out).length} occupancy types → src/damage-curves.js (${(body.length / 1024).toFixed(0)} kB)`);
